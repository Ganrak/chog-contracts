// Who held every Chog Genesis when the launch pool opened. Only a Chog still in the same wallet as in this
// snapshot can win the pool, so spreading Chogs over fresh wallets after the announcement buys nothing.
// Run once when the pool opens:  node scripts/pool-snapshot.mjs
// Writes data/pool-snapshot.json (public, anyone can check it) and netlify/lib/pool-snapshot.mjs (read by the payout).
import { writeFileSync } from 'node:fs';
import { ownersOf, RPC } from '../src/chain.js';
import { SUPPLY } from '../src/traits.js';

const ids = Array.from({ length: SUPPLY }, (_, i) => i + 1);
const block = await (await fetch(RPC, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'eth_blockNumber', params: [] }) })).json();
const owners = {};
for (let i = 0; i < ids.length; i += 225) {
  const part = ids.slice(i, i + 225), got = await ownersOf(part);
  part.forEach((id, k) => { if (got[k]) owners[id] = got[k]; });
  process.stdout.write(`\r${Math.min(ids.length, i + 225)} / ${ids.length}`);
}
const snap = { takenAt: new Date().toISOString(), block: parseInt(block.result, 16), owners };
writeFileSync(new URL('../data/pool-snapshot.json', import.meta.url), JSON.stringify(snap));
writeFileSync(new URL('../netlify/lib/pool-snapshot.mjs', import.meta.url), `// generated by scripts/pool-snapshot.mjs — do not edit\nexport default ${JSON.stringify(snap)};\n`);
console.log(`\nsaved ${Object.keys(owners).length} owners at block ${snap.block}`);
